export function carrierKey(carrier: string): string {
  return carrier.trim().toLowerCase();
}

export default function CarrierLogo({ carrier, size = 28 }: { carrier: string; size?: number }) {
  const known = CARRIERS[carrierKey(carrier)];
  if (!known) {
    return (
      <Box
        sx={{
          width: size,
          height: size,
          borderRadius: 1,
          bgcolor: 'background.elevation2',
          color: 'text.secondary',
          fontSize: size * 0.32,
          fontWeight: 700,
          display: 'inline-flex',
          alignItems: 'center',
          justifyContent: 'center',
          flexShrink: 0,
        }}
      >
        {carrier.slice(0, 4).toUpperCase() || '?'}
      </Box>
    );
  }
  return (
    <Tooltip title={known.label}>
      <Box
        component="span"
        role="img"
        aria-label={known.label}
        sx={{
          width: size,
          height: size,
          borderRadius: 1,
          bgcolor: known.background,
          display: 'inline-flex',
          alignItems: 'center',
          justifyContent: 'center',
          flexShrink: 0,
        }}
      >
        <svg viewBox="0 0 24 24" width={size * 0.72} height={size * 0.72} fill={known.color} aria-hidden="true">
          <path d={known.path} />
        </svg>
      </Box>
    </Tooltip>
  );
}
